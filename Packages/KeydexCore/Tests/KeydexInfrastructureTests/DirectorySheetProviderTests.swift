import Foundation
import KeydexDomain
import KeydexInfrastructure
import Testing

@Suite("Loading sheets from folders")
struct DirectorySheetProviderTests {
    private let root: URL = {
        let url = FileManager.default.temporaryDirectory.appendingPathComponent("keydex-tests-\(UUID().uuidString)")
        try? FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
        return url
    }()

    private func folder(_ name: String, files: [String: String]) throws -> URL {
        let url = root.appendingPathComponent(name)
        try FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
        for (file, text) in files {
            try text.write(to: url.appendingPathComponent(file), atomically: true, encoding: .utf8)
        }
        return url
    }

    @Test("Markdown files are loaded in name order; other files are ignored")
    func loadsMarkdown() throws {
        let user = try folder("user", files: [
            "zsh.md": "# zsh\n- `⌃W` Word", "macos.md": "# macOS\n- `⌃←` Space", "notes.txt": "ignored",
        ])
        let provider = DirectorySheetProvider(directories: [user])
        #expect(provider.sheets.map(\.title) == ["macOS", "zsh"])
    }

    @Test("A user file replaces the bundled file with the same name")
    func override() throws {
        let bundled = try folder("bundled", files: ["zsh.md": "# zsh (bundled)", "macos.md": "# macOS"])
        let user = try folder("user", files: ["ZSH.md": "# zsh (mine)"])
        let provider = DirectorySheetProvider(directories: [bundled, user])
        #expect(Set(provider.sheets.map(\.title)) == ["macOS", "zsh (mine)"])
    }

    @Test("Reload picks up changes, and parsing issues are reported per file")
    func reloadAndIssues() throws {
        let user = try folder("user", files: [:])
        let provider = DirectorySheetProvider(directories: [user])
        #expect(provider.sheets.isEmpty)

        try "# App\n- `⌘?!` Bad".write(to: user.appendingPathComponent("app.md"), atomically: true, encoding: .utf8)
        provider.reload()
        #expect(provider.sheets.map(\.title) == ["App"])
        #expect(provider.files.first?.issues.count == 1)
    }

    @Test("Only the sheets that apply to the app are given for it")
    func filtersByApp() throws {
        let user = try folder("user", files: ["zsh.md": "# zsh\napps: Ghostty", "macos.md": "# macOS"])
        let provider = DirectorySheetProvider(directories: [user])
        let safari = AppInfo(processID: 1, bundleIdentifier: "com.apple.Safari", name: "Safari")
        #expect(provider.sheets(for: safari).map(\.title) == ["macOS"])
    }

    @Test("A missing folder is simply empty")
    func missingFolder() {
        #expect(DirectorySheetProvider(directories: [root.appendingPathComponent("nope")]).sheets.isEmpty)
    }
}

@Suite("Sheets generated by a command")
struct SheetCommandTests {
    private let folder: URL = {
        let url = FileManager.default.temporaryDirectory.appendingPathComponent("keydex-cmd-\(UUID().uuidString)")
        try? FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
        return url
    }()
    private let app = AppInfo(processID: 999_999, bundleIdentifier: "com.example.tool", name: "Tool")

    private func write(_ name: String, _ text: String, executable: Bool = false) throws {
        let url = folder.appendingPathComponent(name)
        try text.write(to: url, atomically: true, encoding: .utf8)
        if executable {
            try FileManager.default.setAttributes([.posixPermissions: 0o755], ofItemAtPath: url.path)
        }
    }

    @Test("The command runs from the sheet's folder, knows the app, and its output completes the sheet")
    func generatesSections() throws {
        try write("tool.md", "# Tool\napps: com.example.tool\ncommand: ./tool.sh\n## Manual\n- `⌘M` Written by hand")
        try write("tool.sh", "#!/bin/sh\necho '## Generated'\necho \"- \\`⌘J\\` For $KEYDEX_APP_NAME ($KEYDEX_APP_BUNDLE_ID)\"", executable: true)
        let sheets = DirectorySheetProvider(directories: [folder]).sheets(for: app)
        #expect(sheets.count == 1)
        #expect(sheets[0].sections.map(\.title) == ["Generated", "Manual"])
        #expect(sheets[0].sections[0].entries.first?.title == "For Tool (com.example.tool)")
    }

    @Test("A failing or slow command leaves the sheet as written")
    func failingCommands() throws {
        try write("fails.md", "# Fails\napps: Tool\ncommand: exit 3\n- `⌘M` Manual")
        try write("slow.md", "# Slow\napps: Tool\ncommand: sleep 5\n- `⌘N` Manual")
        let provider = DirectorySheetProvider(directories: [folder], commandTimeout: 0.3)
        let start = Date()
        let sheets = provider.sheets(for: app)
        #expect(Date().timeIntervalSince(start) < 2)
        #expect(sheets.map { $0.sections.flatMap(\.entries).map(\.title) } == [["Manual"], ["Manual"]])
    }

    @Test("A command leaving a background process does not block the read")
    func backgroundProcess() throws {
        try write("bg.md", "# Bg\napps: Tool\ncommand: (sleep 5 &); echo '- `⌘J` Done'")
        let start = Date()
        let sheets = DirectorySheetProvider(directories: [folder]).sheets(for: app)
        #expect(Date().timeIntervalSince(start) < 2)
        #expect(sheets.first?.sections.first?.entries.first?.title == "Done")
    }

    @Test("The output is reused for a short while, then the command runs again")
    func cache() throws {
        try write("count.md", "# Count\napps: Tool\ncommand: echo run >> runs.log; echo '- `⌘J` J'")
        let provider = DirectorySheetProvider(directories: [folder], commandCacheDuration: 0.3)
        _ = provider.sheets(for: app)
        _ = provider.sheets(for: app)
        Thread.sleep(forTimeInterval: 0.4)
        _ = provider.sheets(for: app)
        let runs = try String(contentsOf: folder.appendingPathComponent("runs.log"), encoding: .utf8)
        #expect(runs.split(separator: "\n").count == 2)
    }

    @Test("Commands only run for the apps the sheet applies to")
    func onlyForItsApps() throws {
        try write("other.md", "# Other\napps: Other\ncommand: echo run >> runs.log")
        _ = DirectorySheetProvider(directories: [folder]).sheets(for: app)
        #expect(!FileManager.default.fileExists(atPath: folder.appendingPathComponent("runs.log").path))
    }
}
